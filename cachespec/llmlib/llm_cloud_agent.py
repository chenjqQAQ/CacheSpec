    def validate_cached_output(self, values, plan, examples_to_validate=[]):
        code_to_write = plan.strip('```python\n').rstrip('```')
        with open('runnable_code.py', 'w') as f:
            f.write(code_to_write)

        _, db_pairs = self.database.get_db(values)

        example_prompt = ""
        for i, (inp, value) in enumerate(db_pairs.items()):
            if i == 1:
                continue

            if len(examples_to_validate) > 0 and value['prompt'] not in examples_to_validate:
                continue

            input_dict = tuple_to_dict_key(inp)

            result = subprocess.run(['python3', 'runnable_code.py', json.dumps(input_dict)], stdout=subprocess.PIPE, text=True)
            answer = result.stdout

            example_prompt += f"\n{i+1}:\n"
            example_prompt += f"Answer from LLM:\n------\n{answer}\n\n"
            example_prompt += f"Ground Truth:\n------\n{value['output']}\n\n"
            example_prompt += "++++++++++++\n\n"

            if len(examples_to_validate) == 0 and i >= self.num_examples_for_cache:
                break

        prompt_template = CACHE_VALIDATOR_PROMPT_PREFIX + example_prompt
        prompt = PromptTemplate.from_template(replace_braces(prompt_template))
        self.validator_llm_chain = LLMChain(llm=self.validator_llm, prompt=prompt, callbacks=self.callbacks)

        validation = self.validator_llm_chain.predict(prompt=self.validator_llm_chain.prompt)
        
        return validation
    

    def validate_prompt_with_regex(self, prompt, regex):
        code_to_write = regex.strip('```python\n').rstrip('```')
        with open('runnable_code.py', 'w') as f:
            f.write(code_to_write)

        result = subprocess.run(['python3', 'runnable_code.py', prompt.replace('\n', '')], stdout=subprocess.PIPE, text=True)
        answer = result.stdout
        return bool(answer)
    

    def validate_regex(self, values, regex):
        _, db_pairs = self.database.get_db(values)

        count = 0
        validated_prompts = []
        for inp, value in db_pairs.items():
            answer = self.validate_prompt_with_regex(value['prompt'], regex)
            print(answer)
            if answer:
                count += 1  
                validated_prompts.append(value['prompt'])

        if count >= self.num_examples_for_cache or count == len(db_pairs):
            validation = {"valid": 1,
                          "validated_prompts": validated_prompts,
                          "reason": "Required number of prompts match the regex."}
        else:
            validation = {"valid": 0, 
                          "reason": "Only '{}' out of '{}' prompts match the regex.".format(count, len(db_pairs))}
        
        return validation


    def generate_cache(self, inputs, values):

        _, regex = self.generate_regex(values)
        validation_result = self.validate_regex(values, regex)
        if not validation_result['valid']:
            return self.results
        
        key, plan = self.generate_plan(values, regeneration=False)
        self.results["num_iters_for_cache"] += 1

        i = 0
        while True:
            print("########## Plan ##########")
            print(plan)

            # Validate the output generated by the LLM
            print("########## Validating the output ##########")
            validation = self.validate_cached_output(values, plan, validation_result['validated_prompts'])
            i += 1
            
            print(validation)
            json_validation = json.loads(validation.strip('```json\n').rstrip('```'))
            
            isValid = json_validation['valid']

            
            if isValid:
                # Set the cache for the data
                if os.path.exists(self.cache_path) and os.path.getsize(self.cache_path) >= CACHE_LIMIT:
                    while os.path.getsize(self.cache_path) >= CACHE_LIMIT:
                        cache = self.global_cache.get_entire_cache()
                        cache_keys = cache.keys()
                        cache_count_dict = dict()
                        for key in cache_keys:
                            cache_count_dict[key] = cache[key]['count']

                        cache_count_dict = sorted(cache_count_dict.items(), key=lambda x: x[1])  # Will be of the form [(key, count), (key, count), ...], sorted in an ascending order
                        print(f" ## Cache with key {cache_count_dict[0][0]} is being deleted due to space limit")
                        self.global_cache.delete_cache(cache_count_dict[0][0])

                self.global_cache.set_cache(int(key), {"plan":plan, "regex":regex})
                return self.results
            else:
                if i >= self.num_validation_chance:
                    return self.results
                key, plan = self.generate_plan(values, regeneration=True, reason=json_validation['reason'])

    



