class CacheGenerator:

    def __init__(self, 
                 cfg: DictConfig,
                 global_cache: GlobalCache,
                 database: ClusterDatabase,
                 cache_path: str,
                 results: Dict[str, Any] = {},
                 callbacks: Optional[Callbacks] = None,
                 num_validation_chance: int = 3,
                 num_examples_for_cache: int = 3):
        self.cfg = cfg
        self.global_cache = global_cache
        self.database = database
        self.cache_path = cache_path
        self.callbacks = callbacks
        self.num_validation_chance = num_validation_chance
        self.num_examples_for_cache = num_examples_for_cache
        self.results = results

        self.llm = init_llm(cfg, enable_cache=False)
        self.validator_llm = init_llm(cfg, enable_cache=False)
    

    def generate_plan(self, values, regeneration=False, reason=None):
        key, db_pairs = self.database.get_db(values)
        
        reasoning_inputs = dict()
        example_prompt = ""

        for i, (inp, value) in enumerate(db_pairs.items()):
            example_prompt += f"\n{i+1}:\n"
            example_prompt += f"Prompt Template:\n------------\n{value['prompt_template']}\n\n"
            example_prompt += f"Inputs:\n------\n"
            for elem in inp:
                example_prompt += f"KEY -> {elem[0]}\nVALUE -> {elem[1]}\n\n"
            example_prompt += f"\nOutput:\n------\n{value['output']}\n\n\n"

            if i >= self.num_examples_for_cache:
                break
        
        if regeneration:
            reasoning_inputs["reason"] = reason 
            prompt_template = CACHE_GENERATOR_PROMPT_PREFIX + example_prompt + CACHE_REGENERATOR_PROMPT.format(**reasoning_inputs) + CACHE_GENERATOR_PROMPT_SUFFIX
        else:
            prompt_template = CACHE_GENERATOR_PROMPT_PREFIX + example_prompt + CACHE_GENERATOR_PROMPT_SUFFIX

        prompt = PromptTemplate.from_template(replace_braces(prompt_template))
        print(reasoning_inputs)

        self.llm_chain = LLMChain(llm=self.llm, prompt=prompt, callbacks=self.callbacks)

        plan = self.llm_chain.predict(prompt=self.llm_chain.prompt, **reasoning_inputs)

        self.results["num_abs_calls_for_cache"] += 1
        self.results["caching_retry_per_cluster"][str(key)] = self.results.get("caching_retry_per_cluster", {}).get(str(key), 0) + 1

        if str(key) not in self.results.get("caching_retry_token_length_per_cluster", {}):
            self.results["caching_retry_token_length_per_cluster"][str(key)] = []
        self.results["caching_retry_token_length_per_cluster"][str(key)].append({'input': compute_token_length(prompt_template), 'output': compute_token_length(plan)})

        return key, plan
    

