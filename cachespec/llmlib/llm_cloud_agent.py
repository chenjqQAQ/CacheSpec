    def find_cache_key(self, value):
        key, _ = self.database.get_db(value)
        return key


    def get_formatted_prompt(self, prompt, inputs):
        formatted_prompt = None

        # Create formatted prompt
        if isinstance(prompt, ChatPromptTemplate):
            prompt_template = ""
            for p in prompt.messages:
                prompt_template += p.prompt.template + "\n"
            formatted_prompt = prompt.format(**inputs)
        else:
            prompt_template = prompt.template
            formatted_prompt = prompt.format(**inputs)

        return prompt_template, formatted_prompt
    

