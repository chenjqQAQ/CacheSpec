    def find_and_validate_all_cache(self, prompt):
        CACHE_FIND_START_TIME = time.time()

        cache = self.global_cache.get_entire_cache()
        cache_keys = cache.keys()

        validated_caches = {}
        for key in cache_keys:
            validation_result = self.cacheGen.validate_prompt_with_regex(prompt, cache[key]['regex'])
            if 'plan' not in cache[key]:
                validation_result = False

            if validation_result:
                validated_caches[key] = cache[key]

        CACHE_FIND_END_TIME = time.time()

        return validated_caches, (CACHE_FIND_END_TIME - CACHE_FIND_START_TIME)



