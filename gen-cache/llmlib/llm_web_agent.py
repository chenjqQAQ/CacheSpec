    def llm_predict_no_key(self,
                           inputs: dict,
                           llm_chain: Optional[Union[LLMChain, openai.lib.azure.AzureOpenAI]] = None, 
                           callbacks: Optional[Callbacks] = None):
        
        USE_LLM = True
        cached_key_used = None
        cached_answer = None

        formatted_prompt, prompt_template = self.get_formtatted_prompt(inputs, llm_chain)
        input_token_length = compute_token_length(formatted_prompt)

        if self.CACHING_ENABLED:
            # find, validate and generate cached answer only if caching is enabled
            if self.version == "v1":
                caches, cache_find_time = self.find_and_validate_cache(formatted_prompt)
            elif self.version == "v2":
                caches, cache_find_time = self.find_and_validate_all_cache(formatted_prompt)
            self.incident_metric["cache_find_time"].append(cache_find_time)

            CACHE_USE_START_TIME = time.time()
            # Loop over all the caches to find the one that matches the prompt
            for key in caches.keys():
                print("#### Caches Retrieved ####")
                print("### Cache Key: ", key)

                cache = caches[key]
                self.results["num_cache_hits"] += 1
                plan = cache["plan"]
                print("Plan: ", plan)

                code_to_write = plan.strip('```python\n').rstrip('```')
                with open('runnable_code.py', 'w') as f:
                    f.write(code_to_write)

                try:
                    result = subprocess.run(['python3', 'runnable_code.py', formatted_prompt], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
                except subprocess.CalledProcessError as e:
                    print("Cached Code stopped running with error ", e.stderr)  
                else:
                    cached_answer = result.stdout
                    print('Answer:', cached_answer)
                    if is_valid_dictionary(cached_answer) or "None" not in cached_answer:
                        select_item = True
                        try:
                            ans = json.loads(cached_answer)
                            if not eval(ans['function_call']['arguments'])['item_id'].startswith('B'):
                                select_item = False
                        except:
                            pass

                        if select_item:
                            USE_LLM = False

                            # replace null with none
                            cached_answer = cached_answer.replace('null', 'None')
                            cached_key_used = key
                            CACHE_USE_END_TIME = time.time()
                            self.incident_metric["cache_call_time"].append(CACHE_USE_END_TIME - CACHE_USE_START_TIME)
                            self.incident_metric["sum_diagnosis_time"] += CACHE_USE_END_TIME - CACHE_USE_START_TIME
                            break
                    

        if not USE_LLM:
            # Logging results
            self.results["num_accurate_cache_hits"] += 1
            self.results["cache_reuse"][str(cached_key_used)] = self.results.get("cache_reuse", {}).get(str(cached_key_used), 0) + 1
            self.incident_metric["num_accurate_cache_hits"] += 1
            self.incident_metric["sum_input_token_length_for_semantic_cache"] += input_token_length
            self.incident_metric["sum_output_token_length_for_semantic_cache"] += compute_token_length(cached_answer)

            print("Returning the Cached Answer: ", cached_answer)
            return cached_answer, cached_key_used, True
        else:
            print("*********** USING LLM ***********")
            LLM_USE_START_TIME = time.time()

            if isinstance(llm_chain, LLMChain):
                # Use LLM to predict the response to the prompt
                answer = llm_chain.predict(prompt=llm_chain.prompt, **inputs, callbacks=callbacks)
                print('Answer:', answer)

                LLM_USE_END_TIME = time.time()

                llm_call_time = LLM_USE_END_TIME - LLM_USE_START_TIME
                self.incident_metric["sum_diagnosis_time"] += llm_call_time

                db_inputs = dict_to_tuple_key(inputs)
                database_val = {"prompt_template": prompt_template, 
                                "prompt": formatted_prompt, 
                                "output": answer}
                
            elif isinstance(llm_chain, openai.lib.azure.AzureOpenAI):
                # Use LLM to predict the response to the prompt
                if inputs["functions"] is not None:
                    response = llm_chain.chat.completions.create(
                        model=inputs["model"],
                        messages=inputs["messages"],
                        max_tokens=inputs["max_tokens"],
                        temperature=inputs["temperature"],
                        top_p=inputs["top_p"],
                        n=inputs["n"],
                        stop=inputs["stop"],
                        functions=inputs["functions"], function_call=inputs["function_call"] if inputs["function_call"] is not None else "auto",
                    )
                else:
                    response = llm_chain.chat.completions.create(
                        model=inputs["model"],
                        messages=inputs["messages"],
                        max_tokens=inputs["max_tokens"],
                        temperature=inputs["temperature"],
                        top_p=inputs["top_p"],
                        n=inputs["n"],
                        stop=inputs["stop"],
                    )

                answer = str(response.choices[0].message.dict())

                LLM_USE_END_TIME = time.time()

                llm_call_time = LLM_USE_END_TIME - LLM_USE_START_TIME
                self.incident_metric["sum_diagnosis_time"] += llm_call_time

                key_input = dict()
                key_input["key"] = str(hash(str(key_input)))
                db_inputs = dict_to_tuple_key(key_input)
                database_val = {"prompt_template": str(inputs["messages"][0]), 
                                "prompt": str(inputs["messages"]), 
                                "output": answer}

            elif isinstance(llm_chain, gptcache.adapter.langchain_models.LangChainChat):
                print("...In GPTCache Branch...")
                response = llm_chain([inputs["messages"][0]])
                answer = response.content
                print(answer)

                LLM_USE_END_TIME = time.time()
                llm_call_time = LLM_USE_END_TIME - LLM_USE_START_TIME
                self.incident_metric["sum_diagnosis_time"] += llm_call_time

                key_input = dict()
                key_input["key"] = str(hash(str(key_input)))
                db_inputs = str(hash(str(key_input)))
                database_val = {"prompt_template": str(inputs["messages"][0]), 
                                "prompt": str(inputs["messages"][1]), 
                                "output": answer}

            elif llm_chain is None:
                # answer is in the input dictionary itself
                answer = str(inputs["response"])

                LLM_USE_END_TIME = time.time()
                llm_call_time = LLM_USE_END_TIME - LLM_USE_START_TIME
                self.incident_metric["sum_diagnosis_time"] += llm_call_time

                key_input = dict()
                key_input["key"] = str(hash(str(key_input)))
                db_inputs = str(hash(str(key_input)))
                database_val = {"prompt_template": str(inputs["messages"][0]), 
                                "prompt": str(inputs["messages"]), 
                                "output": answer}
            
            # Check whether llm call time is over a threshold or not. 
            # If no, then exact caching was done and update the metrics accordingly
            if llm_call_time > LLM_EXACT_CACHE_TIME_THRESHOLD:
                print("#### NOT Exact Cache ####")
                self.incident_metric["sum_input_token_length_for_llm"] += input_token_length
                self.incident_metric["sum_output_token_length_for_llm"] += compute_token_length(answer)
                self.incident_metric["llm_call_time"].append(llm_call_time)
            else:
                print("#### Exact Cache ####")
                self.results["num_exact_cache_hits"] += 1
                self.incident_metric["num_exact_cache_hits"] += 1
                self.incident_metric["sum_input_token_length_for_exact_cache"] += input_token_length
                self.incident_metric["sum_output_token_length_for_exact_cache"] += compute_token_length(answer)
                self.incident_metric["exact_cache_call_time"].append(llm_call_time)

            if self.CACHING_ENABLED:
                cache_keys = caches.keys()

                if os.path.exists(self.database_path) and os.path.getsize(self.database_path) >= DB_LIMIT:
                    # if database size is more than limit, then don't add entry to the database
                    print("Database size is more than limit, skipping database entry")
                    pass
                else:
                    DB_ENTRY_START_TIME = time.time()
                    ret_val, key = self.database.set_db(db_inputs, database_val, cache_keys)
                    DB_ENTRY_END_TIME = time.time()
                    
                    self.incident_metric["db_entry_time"].append(DB_ENTRY_END_TIME - DB_ENTRY_START_TIME)

                    # Check if caching retries have exceeded some threshold
                    if str(key) not in self.results["caching_retry_per_cluster"] or \
                        (str(key) in self.results["caching_retry_per_cluster"] and self.results["caching_retry_per_cluster"][str(key)] <= CACHE_RETRY_THRESHOLD):
                        
                        if key not in self.num_caching_trials:
                            self.num_caching_trials[key] = 0
                            self.num_caching_exclusion[key] = 0
                        
                        # Check if consecutive caching trials have exceeded a threhsold or not
                        print(f"NUM CACHING TRIALS: {self.num_caching_trials[key]}  |  NUM CACHING EXCLUSION: {self.num_caching_exclusion[key]}")
                        # Switching when to again try caching
                        if self.num_caching_trials[key] >= self.CACHING_MAX_TRIALS:
                            self.num_caching_exclusion[key] += 1

                        if self.num_caching_exclusion[key] >= self.CACHING_MAX_PAUSES:
                            self.num_caching_exclusion[key] = 0
                            self.num_caching_trials[key] = 0

                        # If the number of records in the database is greater than the threshold, cache the records
                        print(f"Database len: {self.database.len(key)}  |  num_records_before_caching: {self.num_records_before_caching}")
                        if self.database.len(key) >= self.num_records_before_caching:
                            if key in self.num_caching_trials and self.num_caching_trials[key] < self.CACHING_MAX_TRIALS:
                                self.results = self.cacheGen.generate_cache(database_val, key)
                                self.num_caching_trials[key] += 1
                
            return answer, None, False


    def llm_predict(self, 
                    inputs: dict, 
                    llm_chain: Optional[Union[LLMChain, openai.lib.azure.AzureOpenAI]] = None,  
                    keys: Optional[str] = None,
                    callbacks: Optional[Callbacks] = None):
        
        if keys:
            answer = self.llm_predict_with_key(llm_chain, keys, inputs, callbacks)
        else:
            self.results["total_calls"] += 1
            self.incident_metric["total_calls"] += 1
            answer, cached_key, cache_hit = self.llm_predict_no_key(llm_chain=llm_chain, inputs=inputs, callbacks=callbacks)

        json.dump(self.results, open(self.aggregate_results_file, "w"))
        json.dump(self.incident_metric, open(self.incident_metric_file, "w"))
        print("\n\n ********************************* \n\n")
        
        return answer, cached_key, cache_hit
    

